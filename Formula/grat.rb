class Grat < Formula
  desc "Run approved local development tasks safely"
  homepage "https://github.com/phranck/grat"
  url "https://github.com/phranck/grat/archive/refs/tags/v1.4.0.tar.gz"
  sha256 "6f5a20c226dec0edbf88644886d06d49333b858dafef2cc5571c892b74350087"
  license "MIT"

  bottle do
    root_url "https://github.com/phranck/grat/releases/download/v1.4.0"
    sha256 cellar:       :any_skip_relocation,
           arm64_tahoe:  "88fb15998b9f0c8bfdfa8d89848598c3a650875743a799548d11395e71ef70ae",
           arm64_linux:  "5d596be72f81b2bfc68e072364a5733e7e781af129574bebbeada980324e65db",
           tahoe:        "ececb0f9616cd699b07426dc78d988c3df6ef92ccd34e47b27360005fc61b9b9",
           x86_64_linux: "88ec3faacc1141ed7d536885806a72d6bf04057290b5d8a5e8db5a12065b976b"
  end

  depends_on "go" => :build

  def install
    system "go", "build", *std_go_args(ldflags: "-s -w -X github.com/phranck/grat/internal/version.buildVersion=v#{version}"), "./cmd/grat"
    # The manual is generated by the binary that was just built, so it can only
    # ever describe that binary.
    (buildpath/"grat.1").write Utils.safe_popen_read(bin/"grat", "manual")
    man1.install "grat.1"
  end

  test do
    assert_match "v#{version}", shell_output("#{bin}/grat version")
    assert_match "GRAT 1", (man1/"grat.1").read
  end
end
