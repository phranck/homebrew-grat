class Grat < Formula
  desc "Run approved local development tasks safely"
  homepage "https://github.com/phranck/grat"
  url "https://github.com/phranck/grat/archive/refs/tags/v1.11.2.tar.gz"
  sha256 "6dc6d2ed54ed1589a34453540c64e6e06edfb04e9e6633a464ef92892fa6c297"
  license "MIT"

  bottle do
    root_url "https://github.com/phranck/grat/releases/download/v1.11.2"
    sha256 cellar:       :any_skip_relocation,
           arm64_tahoe:  "f772a68c110a301abcd63457b8970e5f887f6908ac0841729dbcfd763af256a0",
           arm64_linux:  "93859756c2393c15dbc6375c999ace8cf84ac79bc33461705441059db3908298",
           tahoe:        "b0d44cf669e078bd25a02c87d946a715d275974ff9580a74680a6ecf5338be9d",
           x86_64_linux: "90482bf88d3978c80650b61cfd9757378c4cefb6291bd978b9589b3611197500"
  end

  depends_on "go" => :build

  def install
    system "go", "build", *std_go_args(ldflags: "-s -w -X github.com/phranck/grat/internal/version.buildVersion=v#{version}"), "./cmd/grat"
    # Both pages are generated by the binary that was just built, so they can
    # only ever describe that binary.
    (buildpath/"grat.1").write Utils.safe_popen_read(bin/"grat", "manual")
    (buildpath/"grat.config.7").write Utils.safe_popen_read(bin/"grat", "manual", "grat.config")
    man1.install "grat.1"
    man7.install "grat.config.7"
  end

  test do
    assert_match "v#{version}", shell_output("#{bin}/grat version")
    assert_match "GRAT 1", (man1/"grat.1").read
    assert_match "GRAT.CONFIG 7", (man7/"grat.config.7").read
  end
end
