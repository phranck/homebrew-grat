class Grat < Formula
  desc "Run approved local development tasks safely"
  homepage "https://github.com/phranck/grat"
  url "https://github.com/phranck/grat/archive/refs/tags/v2.2.1.tar.gz"
  sha256 "69b67ee7f08c09905ec040c0b4b8f47f93b0b4091e5d103ed5c3dba6fc52fe54"
  license "MIT"

  bottle do
    root_url "https://github.com/phranck/grat/releases/download/v2.2.1"
    sha256 cellar:       :any_skip_relocation,
           arm64_tahoe:  "0dcb56443cf35c26e7729e90c6ed46e473ee98465f390fd68aaeddf71bdc3e8f",
           arm64_linux:  "e0293d48fe7497a34bef6e81b7c62ba55686bb3d5a228348549d2fd2ca42ab06",
           tahoe:        "5cd0d9d47962cc1cf72728e81f6a1da9656ee9589a6a2730f8985380ecd8b5e6",
           x86_64_linux: "97181a8739e80da43fcf4e0f7ac1ba4ea39437335958fed40b93ddd65b167d61"
  end

  depends_on "go" => :build

  def install
    system "go", "build", *std_go_args(ldflags: "-s -w -X github.com/phranck/grat/v2/internal/version.buildVersion=v#{version}"), "./cmd/grat"
    # Both pages are generated by the binary that was just built, so they can
    # only ever describe that binary.
    (buildpath/"grat.1").write Utils.safe_popen_read(bin/"grat", "manual")
    (buildpath/"grat.config.7").write Utils.safe_popen_read(bin/"grat", "manual", "grat.config")
    man1.install "grat.1"
    man7.install "grat.config.7"
  end

  test do
    assert_match "v#{version}", shell_output("#{bin}/grat version")
    assert_match "GRAT 1", (man1/"grat.1").read
    assert_match "GRAT.CONFIG 7", (man7/"grat.config.7").read
  end
end
